#!/usr/bin/env python3
"""Write docs/installed.md: each skill in this repo and how ~/.agents/skills has it.

Usage: installed-table.py [--check]   (--check exits 1 when the file is stale)
Reads SKILL.md files and the skill lock (source/ref only). Never reads credentials.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
INSTALLED = Path.home() / '.agents/skills'
LOCK = Path.home() / '.agents/.skill-lock.json'
OUT = REPO / 'docs/installed.md'


def tree_hash(folder: Path) -> str:
    h = hashlib.sha256()
    for path in sorted(p for p in folder.rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.name != '.DS_Store'):
        h.update(str(path.relative_to(folder)).encode() + b'\0' + path.read_bytes())
    return h.hexdigest()


def row(name: str, lock: dict) -> str:
    source, target = REPO / 'skills' / name, INSTALLED / name
    if target.is_symlink():
        link = os.readlink(target)
        how = 'link to this repo' if Path(link) == source else 'link elsewhere'
        same = 'yes' if target.resolve() == source.resolve() else ('yes' if target.exists() and tree_hash(target) == tree_hash(source) else 'no')
    elif target.is_dir():
        how = 'copy'
        same = 'yes' if tree_hash(target) == tree_hash(source) else 'no'
    else:
        how, same = 'not installed', '—'
    entry = lock.get(name) or {}
    ref = entry.get('ref') or ('none' if entry else '—')
    origin = entry.get('source') or '—'
    return f'| `{name}` | {how} | {same} | {origin} | {ref} |'


def render() -> str:
    try:
        lock = json.loads(LOCK.read_text()).get('skills', {})
    except (OSError, ValueError):
        lock = {}
    names = sorted(p.name for p in (REPO / 'skills').iterdir() if (p / 'SKILL.md').is_file())
    lines = ['# Installed skills', '',
             'Generated by `skills/maintain-skill-library/scripts/installed-table.py`. Do not edit by hand.', '',
             '| Skill | In ~/.agents/skills | Same files | Lock source | Lock ref |',
             '| --- | --- | --- | --- | --- |']
    lines += [row(name, lock) for name in names]
    return '\n'.join(lines) + '\n'


def main() -> int:
    text = render()
    if '--check' in sys.argv[1:]:
        current = OUT.read_text() if OUT.is_file() else ''
        print('installed.md is current' if current == text else 'installed.md is stale; run installed-table.py')
        return 0 if current == text else 1
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    print(f'wrote {OUT.relative_to(REPO)} ({len(text.splitlines()) - 6} skills)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
